const languageToggle = document.querySelector("[data-lang-toggle]");
const languageMeta = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const content = translations[language];
  document.documentElement.lang = language;
  document.title = content.title;
  languageMeta.content = content.metaDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.innerHTML = content[element.dataset.i18n];
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", content[element.dataset.i18nAriaLabel]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = content[element.dataset.i18nAlt];
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    element.content = content[element.dataset.i18nContent];
  });

  languageToggle.textContent = language === "pt-BR" ? "EN" : "PT";
  languageToggle.setAttribute("aria-label", content.switchLanguage);
  languageToggle.title = content.switchLanguage;
}

languageToggle.addEventListener("click", () => {
  setLanguage(document.documentElement.lang === "pt-BR" ? "en" : "pt-BR");
});
